#!/usr/bin/env bash
# Mint everything this rig needs to be brought up without a single prompt, into
# a gitignored .secrets.env. Idempotent: values already present are kept.
#
#   SECRET_KEY_BASE     signs the dashboard's sessions (≥64 bytes, upstream)
#   TOTP_VAULT_KEY      encrypts TOTP secrets at rest (32 bytes, base64)
#   PLAUSIBLE_EMAIL     the admin account up.sh registers
#   PLAUSIBLE_PASSWORD  …and its password
#   PLAUSIBLE_SITE      the site (data-domain) events are attributed to
#
# WHY A FILE, NOT ENVIRONMENT VARIABLES. Plausible CE seeds no account: whoever
# registers first is the owner, and there is no recovery path without a working
# mailer. A password that exists only in one shell's environment is a dashboard
# that becomes unreachable the moment that shell closes — openreplay-stack
# learned this by having to wipe its volumes. Same convention as this repo's
# other dev secrets (.devcontainer/post-create.sh mints secrets.yaml the same
# way with openssl).
#
# The two Elixir secrets live here rather than in vendor/.env for one reason:
# vendor/ is deleted by `fetch-upstream.sh --force`, and rotating
# SECRET_KEY_BASE under a live database logs every session out and makes
# TOTP secrets undecryptable. up.sh copies them into vendor/.env on every run.
#
# Usage: secrets.sh [--print]
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$HERE/lib.sh"

load_secrets

# A password is about to be written to disk — make sure git can never take it.
# On this branch .claude/ is TRACKED, so only the skill's own .gitignore
# protects this file, and a rule that is present-but-wrong looks exactly like a
# rule that works. Ask git, do not read the file.
guard_gitignored() {
    command -v git >/dev/null 2>&1 || return 0
    git -C "$SKILL_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0
    git -C "$SKILL_DIR" check-ignore -q "$SECRETS_FILE" && return 0
    echo "error: $SECRETS_FILE would be TRACKED by git — refusing to write secrets there." >&2
    echo "       Add '.secrets.env' to $SKILL_DIR/.gitignore first." >&2
    exit 1
}

fresh=0
if [ -z "${SECRET_KEY_BASE:-}" ] || [ -z "${PLAUSIBLE_PASSWORD:-}" ]; then
    fresh=1
    guard_gitignored

    # `tr -d '\r\n'`, NOT `tr -d '\n'`. Git Bash's openssl prints CRLF, so the
    # obvious version leaves a carriage return at the END OF THE VALUE — which
    # is not a line ending any more, it is a byte inside a secret. Plausible
    # then refuses to boot with "TOTP_VAULT_KEY must be Base64 encoded 32 bytes"
    # about a key that decodes to exactly 32 bytes in every tool you check it
    # with. See the long note in lib.sh:load_secrets for why nothing shows it.

    # ≥64 bytes. `openssl rand -base64 48` is upstream's own suggestion.
    SECRET_KEY_BASE="${SECRET_KEY_BASE:-$(openssl rand -base64 48 | tr -d '\r\n')}"
    # Exactly 32 bytes, base64 — Plausible decodes this one and rejects a wrong
    # length at boot rather than at first use.
    TOTP_VAULT_KEY="${TOTP_VAULT_KEY:-$(openssl rand -base64 32 | tr -d '\r\n')}"
    PLAUSIBLE_EMAIL="${PLAUSIBLE_EMAIL:-admin@hackagon.test}"
    PLAUSIBLE_PASSWORD="${PLAUSIBLE_PASSWORD:-$(openssl rand -hex 16 | tr -d '\r\n')}"
    PLAUSIBLE_NAME="${PLAUSIBLE_NAME:-Hackagon Analytics Admin}"
    # RFC 2606 reserves .test for exactly this. It is a LABEL, not a hostname:
    # Plausible attributes an event to a site by matching the tracker's
    # `data-domain` string, and never resolves or contacts it. Using a domain we
    # do not own (hackagon.dev) would work identically and be somebody else's
    # namespace.
    PLAUSIBLE_SITE="${PLAUSIBLE_SITE:-hackagon.test}"

    umask 077
    cat >"$SECRETS_FILE" <<EOF
# Plausible CE dev rig — generated by scripts/secrets.sh, gitignored.
# KEY=value, no quotes; everything after the first '=' is the value.
#
# Survives down.sh. After down.sh --volumes (databases wiped, registration
# reopens) the next up.sh re-creates the same account from these values, which
# is what makes a wipe a recovery path instead of a second lockout.
SECRET_KEY_BASE=$SECRET_KEY_BASE
TOTP_VAULT_KEY=$TOTP_VAULT_KEY
PLAUSIBLE_EMAIL=$PLAUSIBLE_EMAIL
PLAUSIBLE_PASSWORD=$PLAUSIBLE_PASSWORD
PLAUSIBLE_NAME=$PLAUSIBLE_NAME
PLAUSIBLE_SITE=$PLAUSIBLE_SITE
EOF
fi

if [ "$fresh" -eq 1 ] || [ "${1:-}" = "--print" ]; then
    echo "==> Plausible admin credentials ($SECRETS_FILE)"
    echo "    email     ${PLAUSIBLE_EMAIL:-}"
    echo "    password  ${PLAUSIBLE_PASSWORD:-}"
    echo "    site      ${PLAUSIBLE_SITE:-}"
    [ "$fresh" -eq 1 ] && echo "    ⚠ dev-only credentials, shown once — afterwards read the file."
fi
